#!/bin/bash
# Build two small macOS apps in ~/Applications for everyday use:
#
#   Open Oura Service.app  background agent (no window, no Dock icon) that keeps
#                          `oura watch` and `oura dashboard` running and restarts
#                          them if they exit. Its compiled launcher
#                          (tools/macos/ServiceLauncher.swift) stays the parent of
#                          both, so the app owns the Bluetooth and Desktop-folder
#                          permissions: macOS asks once, not after every rebuild.
#   Open Oura.app          what you click: a native window on the dashboard
#                          (tools/macos/OpenOura.swift). It starts the service if
#                          needed; closing the window never stops syncing.
#
# Usage: tools/macos_app.sh /path/to/ring.key   (build `--release` first)
# Logs:  ~/Library/Logs/open_oura/{watch,dashboard}.log
# Stop:  pkill -f "Open Oura Service.app"
set -euo pipefail

KEY=${1:?usage: tools/macos_app.sh /path/to/ring.key}
REPO=$(cd "$(dirname "$0")/.." && pwd)
KEY=$(cd "$(dirname "$KEY")" && pwd)/$(basename "$KEY")
BIN="$REPO/target/release/oura"
DEST="$HOME/Applications"
[ -x "$BIN" ] || { echo "build first: cargo build --release -p oura-cli" >&2; exit 1; }
[ -f "$KEY" ] || { echo "no key file at $KEY" >&2; exit 1; }

# $1 app dir, $2 name, $3 bundle id, $4 executable name, $5 LSUIElement (true/false)
plist() {
  cat >"$1/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>$2</string>
  <key>CFBundleDisplayName</key><string>$2</string>
  <key>CFBundleIdentifier</key><string>$3</string>
  <key>CFBundleExecutable</key><string>$4</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSUIElement</key><$5/>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>NSBluetoothAlwaysUsageDescription</key><string>从 Oura 戒指同步健康数据。</string>
</dict></plist>
EOF
}

SVC="$DEST/Open Oura Service.app"
rm -rf "$SVC" && mkdir -p "$SVC/Contents/MacOS" "$SVC/Contents/Resources"
plist "$SVC" "Open Oura Service" "io.github.open-oura.service" "open-oura-service" true
# the main executable: a launcher that runs supervise.sh and stays its parent
swiftc -O -o "$SVC/Contents/MacOS/open-oura-service" "$REPO/tools/macos/ServiceLauncher.swift"
cat >"$SVC/Contents/Resources/supervise.sh" <<EOF
#!/bin/bash
# Keep the ring sync and the dashboard server running (generated by tools/macos_app.sh).
LOG="\$HOME/Library/Logs/open_oura"
mkdir -p "\$LOG"
cd "$REPO" || exit 1
run() { # log name, then oura arguments; restart whenever it exits
  local name=\$1; shift
  while true; do
    "$BIN" --key-file "$KEY" "\$@" >>"\$LOG/\$name.log" 2>&1
    local rc=\$?
    echo "[\$(date '+%F %T')] \$name exited (\$rc); restarting in 10 s" >>"\$LOG/\$name.log"
    sleep 10
  done
}
run watch watch &
run dashboard dashboard --port 8090 &
trap 'pkill -P \$\$; pkill -f "$BIN --key-file"; exit 0' TERM INT
wait
EOF

VIEW="$DEST/Open Oura.app"
rm -rf "$VIEW" && mkdir -p "$VIEW/Contents/MacOS" "$VIEW/Contents/Resources"
plist "$VIEW" "Open Oura" "io.github.open-oura" "open-oura" false
# the window: a native WebKit view of the dashboard (tools/macos/OpenOura.swift)
swiftc -O -o "$VIEW/Contents/MacOS/open-oura" "$REPO/tools/macos/OpenOura.swift" \
  -framework Cocoa -framework WebKit

# icon for both apps, from tools/macos/icon.swift
TMP=$(mktemp -d)
swiftc -o "$TMP/icon" "$REPO/tools/macos/icon.swift" -framework Cocoa
"$TMP/icon" "$TMP/icon.png"
mkdir "$TMP/AppIcon.iconset"
for s in 16 32 128 256 512; do
  sips -z $s $s "$TMP/icon.png" --out "$TMP/AppIcon.iconset/icon_${s}x${s}.png" >/dev/null
  sips -z $((s * 2)) $((s * 2)) "$TMP/icon.png" --out "$TMP/AppIcon.iconset/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$TMP/AppIcon.iconset" -o "$VIEW/Contents/Resources/AppIcon.icns"
mkdir -p "$SVC/Contents/Resources" && cp "$VIEW/Contents/Resources/AppIcon.icns" "$SVC/Contents/Resources/"
rm -rf "$TMP"

chmod +x "$SVC/Contents/Resources/supervise.sh"
codesign --force -s - "$SVC" "$VIEW" 2>/dev/null || true
echo "built: $VIEW"
echo "       $SVC"
